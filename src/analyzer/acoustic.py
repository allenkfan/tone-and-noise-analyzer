"""Deterministic acoustic measurements: voice activity, silence, technical quality and noise.

Everything runs on the CPU through onnxruntime, with weights pinned in `analyzer.weights`.

    python -m analyzer.acoustic <audio file> ...     # print the measurements as JSON
"""

import functools
import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import onnxruntime as ort

from analyzer.schema import AudioQuality, Severity
from analyzer.weights import DNSMOS, SEGMENTATION, TAGGER, VAD, Weights

SR = 16_000
VAD_FRAME = 512  # Silero's chunk at 16 kHz: 32 ms
VAD_CONTEXT = 64
FRAME_S = VAD_FRAME / SR
TAG_WINDOW = 10 * SR  # the tagger was trained on 10 s clips
TAG_MIN = SR  # shorter windows are tiled up to 1 s
MOS_WINDOW = 144_160  # DNSMOS P.835 input: 9.01 s
SEG_WINDOW, SEG_STEP = 10 * SR, 5 * SR  # pyannote segmentation: 10 s windows, half overlapping
SEG_FRAME = 270  # its output frame: 16.9 ms

# Decision thresholds. Each field's constants were swept on the synthetic tune split (300 clips;
# private/tools/tune_physical.py) by coordinate descent, taking the middle of the best plateau;
# where accuracy was flat within 0.01, the value with more margin against false noise was kept.
# Tune accuracy with these values: silence 0.983, quality 0.870, noise presence 0.907, severity 0.780.
LONG_SILENCE_S = 11.0  # longest stretch without speech
NOISE_TAG_MIN = 0.25  # clip-level score of the strongest noise group
NOISE_SNR_MAX = 20.0  # dB; speech-to-noise ratio below which steady noise counts
NOISE_FLOOR_MIN = -50.0  # dBFS; quieter pauses are barely audible, so pause SNR is ignored
SEVERITY_SNR = (18.0, 6.0)  # speech-to-noise ratio at or below these: medium, high
CLIP_SLIGHT, CLIP_SEVERE = 1.0, 0.1  # peak spread, dB: at or below these the peaks are flattened
BANDWIDTH_SLIGHT, BANDWIDTH_SEVERE = 3000.0, 1700.0  # Hz
LEVEL_SLIGHT, LEVEL_SEVERE = -34.0, -48.0  # active speech level, dBFS
DROPOUT_SLIGHT, DROPOUT_SEVERE = 20.0, 120.0  # dropouts per minute of speech
# Overlap, swept the same way afterwards (tune 0.810). The model measures constructed overlaps
# at about half their length, so 0.4 s measured is roughly 0.6 s or more of real overlap.
OVERLAP_MIN_S = 0.4  # longest stretch with two or more speakers
OVERLAP_RATIO_MIN = 0.005  # fraction of speech with two or more speakers
# Call participants overlap in bursts; a TV, radio or crowd behind them overlaps nearly all the
# time. Above this share of speech, the "second speaker" is taken to be a background voice.
OVERLAP_RATIO_MAX = 0.2  # swept on tune: flat 0.827 to 0.830 from 0.1 to 0.4

# AudioSet class names in the tagger's output order, each with a plain-words noise group ("" = not
# background noise). Generated by tools/make_audioset_groups.py.
_GROUPS = [line.split("\t") for line in
           Path(__file__).with_name("audioset_groups.tsv").read_text(encoding="utf-8").splitlines()]
AUDIOSET_LABELS: list[str] = [name for name, _ in _GROUPS]
NOISE_GROUP: list[str] = [group for _, group in _GROUPS]
GROUPS: list[str] = sorted({g for g in NOISE_GROUP if g})
_GROUP_INDEX = {g: np.array([i for i, x in enumerate(NOISE_GROUP) if x == g]) for g in GROUPS}


@dataclass
class Acoustics:
    duration_s: float
    speech_ratio: float  # fraction of frames VAD calls speech
    longest_silence_s: float  # longest run of non-speech
    snr_db: float | None  # speech energy vs non-speech energy; None without 1 s of speech and 0.5 s of pauses
    clipping_ratio: float  # fraction of samples at or near the clip level
    bandwidth_hz: float  # 99% rolloff of the pre-emphasized speech spectrum
    rms_dbfs: float  # active speech level
    noise_tags: list[tuple[str, float]]  # (group, score) from the tagger, best first
    # decisions, final unless pipeline overrides them
    long_silence_present: bool
    speaker_overlap_present: bool
    audio_quality: AudioQuality
    background_noise_present: bool
    background_noise_severity: Severity
    noise_type_guess: str  # from noise_tags; "" when no noise
    # further measurements
    noise_floor_dbfs: float | None  # level of non-speech away from speech; None if none
    floor_snr_db: float | None  # speech vs the steady floor under it (minimum statistics)
    peak_spread_db: float | None  # spread of the loudest speech peaks; clipping flattens it to 0
    dropouts_per_min: float  # abrupt near-silent gaps inside speech, per minute of speech
    mos_sig: float  # DNSMOS P.835, 1 to 5: speech signal
    mos_bak: float  # background intrusiveness
    mos_ovr: float  # overall
    overlap_ratio: float  # fraction of speech where two or more speakers talk at once
    overlap_longest_s: float  # longest such stretch

    def as_context(self) -> dict:
        """JSON-safe dict for the LLM prompt."""
        out = {}
        for k, v in asdict(self).items():
            if isinstance(v, float):
                v = round(v, 3)
            elif k == "noise_tags":
                v = [[g, round(s, 3)] for g, s in v]
            out[k] = v
        return out


def measure(samples: np.ndarray, sr: int) -> Acoustics:
    """Measure one clip. `samples` is float32 with shape (channels, n) or (n,), at 16 kHz."""
    if sr != SR:
        raise ValueError(f"acoustic.measure needs {SR} Hz audio, got {sr}")
    samples = np.atleast_2d(np.asarray(samples, dtype=np.float32))
    x = samples.mean(axis=0)

    mask = speech_mask(speech_probs(x))
    n = len(mask)
    frames = np.zeros(n * VAD_FRAME, np.float32)
    frames[: len(x)] = x
    frames = frames.reshape(n, VAD_FRAME)
    power = np.mean(frames**2, axis=1)

    speech_power = _mean(power[mask]) if mask.any() else _mean(power)
    far = ~_dilate(mask, 2)  # non-speech at least 64 ms away from speech
    # The median ignores loud minorities such as a ringback tone before the call is answered.
    noise_power = max(float(np.median(power[far])), 1e-10) if far.sum() * FRAME_S >= 0.5 else None
    snr = None
    if noise_power is not None and mask.sum() * FRAME_S >= 1.0:
        snr = _db(max(speech_power - noise_power, 1e-3 * noise_power) / noise_power)
    gaps = [b - a for a, b in _runs(mask) if not mask[a]]

    tags = noise_tags(x)
    sig, bak, ovr = mos(x)
    overlap_ratio, overlap_longest = overlap_stats(*overlap_probs(x))
    ac = Acoustics(
        duration_s=len(x) / SR,
        speech_ratio=float(mask.mean()),
        longest_silence_s=max(gaps, default=0) * FRAME_S,
        snr_db=snr,
        clipping_ratio=max(clipping_ratio(c) for c in samples),
        bandwidth_hz=bandwidth(frames[mask] if mask.sum() >= 10 else frames),
        rms_dbfs=_db(speech_power),
        noise_tags=tags[:5],
        long_silence_present=False,
        speaker_overlap_present=False,
        audio_quality="clear",
        background_noise_present=False,
        background_noise_severity="none",
        noise_type_guess="",
        noise_floor_dbfs=None if noise_power is None else _db(noise_power),
        floor_snr_db=floor_snr_db(frames, mask),
        peak_spread_db=peak_spread_db(x, mask),
        dropouts_per_min=dropouts_per_min(x, mask),
        mos_sig=sig,
        mos_bak=bak,
        mos_ovr=ovr,
        overlap_ratio=overlap_ratio,
        overlap_longest_s=overlap_longest,
    )
    decide(ac)
    return ac


def decide(ac: Acoustics) -> None:
    """Fill the decision fields from the measurements. Quality and noise use separate rules."""
    ac.long_silence_present = ac.longest_silence_s >= LONG_SILENCE_S
    ac.speaker_overlap_present = (ac.overlap_longest_s >= OVERLAP_MIN_S
                                  and OVERLAP_RATIO_MIN <= ac.overlap_ratio <= OVERLAP_RATIO_MAX)

    top_group, top_score = ac.noise_tags[0] if ac.noise_tags else ("", 0.0)
    tagged = top_score >= NOISE_TAG_MIN
    snr = noise_snr(ac)
    steady = snr is not None and snr < NOISE_SNR_MAX
    ac.background_noise_present = tagged or steady
    if not ac.background_noise_present:
        ac.background_noise_severity = "none"
        ac.noise_type_guess = ""
    else:
        snr = NOISE_SNR_MAX if snr is None else snr
        ac.background_noise_severity = ("high" if snr <= SEVERITY_SNR[1] else
                                        "medium" if snr <= SEVERITY_SNR[0] else "low")
        ac.noise_type_guess = top_group if tagged else "background noise"

    spread = ac.peak_spread_db if ac.peak_spread_db is not None else 99.0
    severe = [spread <= CLIP_SEVERE, ac.bandwidth_hz < BANDWIDTH_SEVERE, ac.rms_dbfs < LEVEL_SEVERE,
              ac.dropouts_per_min >= DROPOUT_SEVERE]
    slight = [spread <= CLIP_SLIGHT, ac.bandwidth_hz < BANDWIDTH_SLIGHT, ac.rms_dbfs < LEVEL_SLIGHT,
              ac.dropouts_per_min >= DROPOUT_SLIGHT]
    ac.audio_quality = ("severely_impaired" if any(severe) or sum(slight) >= 2 else
                        "slightly_impaired" if any(slight) else "clear")


def noise_snr(ac: Acoustics) -> float | None:
    """The worse of two speech-to-noise estimates: the pauses (when they are audible at all) and
    the steady floor under speech, which still sees noise that suppression mutes in the pauses."""
    estimates = [ac.floor_snr_db] if ac.floor_snr_db is not None else []
    if ac.snr_db is not None and ac.noise_floor_dbfs is not None and ac.noise_floor_dbfs > NOISE_FLOOR_MIN:
        estimates.append(ac.snr_db)
    return min(estimates, default=None)


# ---------------------------------------------------------------- models

@functools.cache
def _session(w: Weights) -> ort.InferenceSession:
    opts = ort.SessionOptions()
    opts.intra_op_num_threads = 2
    opts.inter_op_num_threads = 1
    opts.log_severity_level = 3
    return ort.InferenceSession(w.path(), opts, providers=["CPUExecutionProvider"])


def speech_probs(x: np.ndarray) -> np.ndarray:
    """Silero speech probability for each 32 ms frame of mono 16 kHz audio."""
    sess = _session(VAD)
    n = -(-len(x) // VAD_FRAME)
    frames = np.zeros(n * VAD_FRAME, np.float32)
    frames[: len(x)] = x
    frames = frames.reshape(n, VAD_FRAME)
    state = np.zeros((2, 1, 128), np.float32)
    context = np.zeros((1, VAD_CONTEXT), np.float32)
    sr = np.array(SR, dtype=np.int64)
    probs = np.empty(n, np.float32)
    for i in range(n):
        chunk = np.concatenate([context, frames[i : i + 1]], axis=1)
        out, state = sess.run(None, {"input": chunk, "state": state, "sr": sr})
        probs[i] = out[0, 0]
        context = chunk[:, -VAD_CONTEXT:]
    return probs


def speech_mask(probs: np.ndarray, threshold: float = 0.5, min_speech_s: float = 0.25,
                min_gap_s: float = 0.1, pad_s: float = 0.03) -> np.ndarray:
    """Frame-level speech decision with Silero's hysteresis and duration rules."""
    low = threshold - 0.15
    mask = np.zeros(len(probs), bool)
    on = False
    for i, p in enumerate(probs):
        on = p >= threshold or (on and p >= low)
        mask[i] = on
    for start, end in _runs(mask):  # close short gaps
        if not mask[start] and start > 0 and end < len(mask) and (end - start) * FRAME_S < min_gap_s:
            mask[start:end] = True
    for start, end in _runs(mask):  # drop short bursts
        if mask[start] and (end - start) * FRAME_S < min_speech_s:
            mask[start:end] = False
    return _dilate(mask, int(round(pad_s / FRAME_S)))


def tag_windows(x: np.ndarray) -> np.ndarray:
    """AudioSet scores, shape (windows, 527), for consecutive 10 s windows."""
    sess = _session(TAGGER)
    out = []
    for start in range(0, max(len(x), 1), TAG_WINDOW):
        seg = x[start : start + TAG_WINDOW]
        if len(seg) < TAG_MIN:
            if start > 0 and len(seg) < TAG_MIN // 2:
                break  # a short tail adds little; the previous window covered most of it
            seg = np.resize(seg, TAG_MIN) if len(seg) else np.zeros(TAG_MIN, np.float32)
        out.append(sess.run(None, {"input_audio": seg[None].astype(np.float32)})[0][0])
    return np.stack(out)


def noise_tags(x: np.ndarray) -> list[tuple[str, float]]:
    """Noise groups by their strongest score in any window, best first."""
    scores = tag_windows(x).max(axis=0)
    ranked = sorted(((g, float(scores[idx].max())) for g, idx in _GROUP_INDEX.items()),
                    key=lambda t: -t[1])
    return [(g, s) for g, s in ranked if s >= 0.01]


def overlap_probs(x: np.ndarray, batch: int = 8) -> tuple[np.ndarray, np.ndarray]:
    """Per 16.9 ms frame: probability of any speech, and of two or more speakers at once.

    pyannote segmentation-3.0 scores 10 s windows in a powerset of up to three local speakers;
    the three pair classes are overlap. Half-overlapping windows are averaged frame by frame.
    """
    sess = _session(SEGMENTATION)
    n_frames = max(-(-len(x) // SEG_FRAME), 1)
    starts = list(range(0, max(len(x) - SEG_WINDOW, 0) + 1, SEG_STEP))
    if starts[-1] + SEG_WINDOW < len(x):
        starts.append(len(x) - SEG_WINDOW)
    speech, overlap, count = (np.zeros(n_frames) for _ in range(3))
    for i in range(0, len(starts), batch):
        chunk = starts[i : i + batch]
        windows = np.zeros((len(chunk), 1, SEG_WINDOW), np.float32)
        for k, s in enumerate(chunk):
            seg = x[s : s + SEG_WINDOW]
            windows[k, 0, : len(seg)] = seg
        logits = sess.run(None, {"input_values": windows})[0]
        p = np.exp(logits - logits.max(axis=2, keepdims=True))
        p /= p.sum(axis=2, keepdims=True)
        for k, s in enumerate(chunk):
            idx = ((s + np.arange(p.shape[1]) * (SEG_WINDOW / p.shape[1])) // SEG_FRAME).astype(int)
            keep = idx < min(n_frames, -(-(s + min(SEG_WINDOW, len(x) - s)) // SEG_FRAME))
            np.add.at(speech, idx[keep], 1 - p[k, keep, 0])
            np.add.at(overlap, idx[keep], p[k, keep, 4:].sum(axis=1))
            np.add.at(count, idx[keep], 1)
    count = np.maximum(count, 1)
    return speech / count, overlap / count


def overlap_stats(speech: np.ndarray, overlap: np.ndarray, min_gap_s: float = 0.1) -> tuple[float, float]:
    """(fraction of speech frames in overlap, longest overlap stretch in seconds)."""
    on = overlap > 0.5
    gap = int(min_gap_s * SR / SEG_FRAME)
    for a, b in _runs(on):  # bridge flickers inside one overlap
        if not on[a] and a > 0 and b < len(on) and b - a <= gap:
            on[a:b] = True
    longest = max((b - a for a, b in _runs(on) if on[a]), default=0)
    talking = speech > 0.5
    return float((on & talking).sum() / max(talking.sum(), 1)), longest * SEG_FRAME / SR


def mos(x: np.ndarray) -> tuple[float, float, float]:
    """DNSMOS P.835 (SIG, BAK, OVRL) averaged over non-overlapping 9 s windows."""
    sess = _session(DNSMOS)
    if len(x) < MOS_WINDOW:
        x = np.resize(x, MOS_WINDOW) if len(x) else np.zeros(MOS_WINDOW, np.float32)
    n = len(x) // MOS_WINDOW
    starts = np.linspace(0, len(x) - MOS_WINDOW, n).astype(int) if n > 1 else [0]
    batch = np.stack([x[s : s + MOS_WINDOW] for s in starts]).astype(np.float32)
    raw = sess.run(None, {"input_1": batch})[0].mean(axis=0)
    sig = np.poly1d([-0.08397278, 1.22083953, 0.0052439])(raw[0])
    bak = np.poly1d([-0.13166888, 1.60915514, -0.39604546])(raw[1])
    ovr = np.poly1d([-0.06766283, 1.11546468, 0.04602535])(raw[2])
    return float(sig), float(bak), float(ovr)


# ---------------------------------------------------------------- signal measures

def clipping_ratio(x: np.ndarray) -> float:
    """Fraction of samples within 5% of the clip level.

    The clip level is the amplitude at the 99.99th percentile, so a few codec overshoots past
    the plateau don't hide it. Unclipped speech has a thin tail there; clipped speech piles up.
    """
    a = np.abs(x)
    level = np.quantile(a, 0.9999) if len(a) else 0.0
    if level <= 1e-4:
        return 0.0
    return float(np.mean(a >= 0.95 * level))


def floor_snr_db(frames: np.ndarray, mask: np.ndarray, block_s: float = 0.5) -> float | None:
    """Speech level against the steady noise floor under it, by minimum statistics.

    In each frequency band the smoothed power drops to the floor between syllables, so the
    minimum over about 1.5 s tracks steady noise even where suppression mutes the pauses.
    """
    if mask.sum() * FRAME_S < 1.0:
        return None
    power = np.abs(np.fft.rfft(frames * np.hanning(frames.shape[1]), axis=1)) ** 2
    smooth = np.empty_like(power)
    smooth[0] = power[0]
    for i in range(1, len(power)):
        smooth[i] = 0.7 * smooth[i - 1] + 0.3 * power[i]
    b = max(int(block_s / FRAME_S), 1)
    nb = -(-len(smooth) // b)
    padded = np.concatenate([smooth, np.repeat(smooth[-1:], nb * b - len(smooth), axis=0)])
    block_min = padded.reshape(nb, b, -1).min(axis=1)
    near = np.minimum(np.minimum(block_min, np.roll(block_min, 1, axis=0)), np.roll(block_min, -1, axis=0))
    floor = np.repeat(near, b, axis=0)[: len(smooth)].sum(axis=1)
    speech = power[mask].sum(axis=1).mean()
    noise = max(1.5 * float(np.median(floor[mask])), 1e-12)
    return _db(max(speech - noise, 1e-3 * noise) / noise)


def peak_spread_db(x: np.ndarray, mask: np.ndarray, win: int = 128) -> float | None:
    """dB between the 99.5th and 95th percentile of 8 ms peaks in speech.

    Speech peaks vary by several dB. Clipping flattens the loudest against a ceiling, and that
    survives a codec's smearing of the waveform, which sample counts at full scale do not.
    """
    n = len(x) // win
    in_speech = np.repeat(mask, VAD_FRAME // win)[:n]
    peaks = np.abs(x[: len(in_speech) * win]).reshape(-1, win).max(axis=1)[in_speech]
    if len(peaks) < 100 or peaks.max() <= 0:
        return None
    peaks = peaks[peaks > 0.1 * peaks.max()]
    hi, lo = np.percentile(peaks, [99.5, 95])
    return 20 * float(np.log10(hi / lo)) if lo > 0 else None


def bandwidth(frames: np.ndarray) -> float:
    """99% rolloff of the pre-emphasized long-term spectrum. Muffled or band-limited speech is low."""
    y = np.concatenate([frames[:, :1], frames[:, 1:] - 0.97 * frames[:, :-1]], axis=1)
    spec = (np.abs(np.fft.rfft(y * np.hanning(y.shape[1]), axis=1)) ** 2).mean(axis=0)
    if spec.sum() <= 0:
        return 0.0
    freqs = np.fft.rfftfreq(y.shape[1], 1 / SR)
    return float(freqs[np.searchsorted(np.cumsum(spec) / spec.sum(), 0.99)])


def dropouts_per_min(x: np.ndarray, mask: np.ndarray, sub: int = 128) -> float:
    """Abrupt drops to near silence, 8 to 120 ms long, inside speech: packet loss and gating."""
    assert VAD_FRAME % sub == 0, "sub-frames must tile the VAD frames or the mask drifts"
    n = len(x) // sub
    if n == 0 or not mask.any():
        return 0.0
    level = 10 * np.log10(np.mean(x[: n * sub].reshape(n, sub) ** 2, axis=1) + 1e-12)
    in_speech = np.repeat(mask, VAD_FRAME // sub)[:n]
    if len(in_speech) < n:
        in_speech = np.pad(in_speech, (0, n - len(in_speech)))
    speech_level = np.median(level[in_speech])
    dead = in_speech & (level < min(speech_level - 45, -70))
    count = 0
    for a, b in _runs(dead):
        if dead[a] and (b - a) * sub <= 0.12 * SR and a > 0 and b < n and level[a - 1] > speech_level - 25 \
                and level[b] > speech_level - 25:
            count += 1
    return count / (in_speech.sum() * sub / SR / 60)


def _runs(mask: np.ndarray) -> list[tuple[int, int]]:
    """Half-open [start, end) runs of equal values."""
    if len(mask) == 0:
        return []
    edges = np.flatnonzero(np.diff(mask.astype(np.int8))) + 1
    bounds = np.concatenate([[0], edges, [len(mask)]])
    return list(zip(bounds[:-1].tolist(), bounds[1:].tolist()))


def _dilate(mask: np.ndarray, k: int) -> np.ndarray:
    out = mask.copy()
    for s in range(1, k + 1):
        out[s:] |= mask[:-s]
        out[:-s] |= mask[s:]
    return out


def _mean(a: np.ndarray) -> float:
    return float(np.mean(a)) if len(a) else 0.0


def _db(power: float) -> float:
    return 10 * float(np.log10(max(power, 1e-10)))


def main(argv: list[str] | None = None) -> None:
    from analyzer.audio import load_audio

    for path in argv if argv is not None else sys.argv[1:]:
        print(json.dumps({"name": Path(path).name, **measure(load_audio(Path(path)), SR).as_context()}))


if __name__ == "__main__":
    main()
